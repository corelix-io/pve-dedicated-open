# First-boot script generation for post-install configuration
# shellcheck shell=bash
#
# The generated script runs once on the real hardware (Proxmox
# proxmox-first-boot service, ordering "fully-up"). Install-time values are
# injected as %q-quoted shell variables in a single block at the top; every
# other section is a quoted heredoc, so nothing is expanded twice.

# Placeholder for the WAN NIC name in the rendered interfaces file. The
# first-boot script replaces it with the NIC that carries the rescue MAC.
readonly FIRSTBOOT_WAN_PLACEHOLDER="__PVE_WAN_IFACE__"

# Emit `NAME=<%q-quoted value>` lines.
_fb_var() {
    local name="$1"
    local value="$2"
    printf '%s=%q\n' "$name" "$value"
}

# Emit `cat > PATH <<'DELIM' ... DELIM` with CONTENT verbatim.
_fb_write_file() {
    local path="$1"
    local delim="$2"
    local content="$3"
    if [[ $'\n'"${content}"$'\n' == *$'\n'"${delim}"$'\n'* ]]; then
        die "first-boot: content for ${path} contains the heredoc delimiter ${delim}"
    fi
    printf "cat > %q <<'%s'\n%s\n%s\n" "$path" "$delim" "$content" "$delim"
}

# Pure helper: ZFS ARC limits in bytes for TOTAL_MB of host RAM and an
# optional ARC max override in MiB. Echoes "<min_bytes> <max_bytes>".
#   max: override, else 15% of RAM (at least 2 GiB)
#   min: 5% of RAM (at least 1 GiB), never more than half of max
firstboot_zfs_arc_limits() {
    local total_mb="${1:-0}"
    local override_mib="${2:-}"
    local mib=$(( 1024 * 1024 ))

    local max_b
    if [[ "$override_mib" =~ ^[0-9]+$ ]] && (( 10#$override_mib > 0 )); then
        max_b=$(( 10#$override_mib * mib ))
    else
        max_b=$(( total_mb * mib * 15 / 100 ))
        if (( max_b < 2048 * mib )); then max_b=$(( 2048 * mib )); fi
    fi

    local min_b=$(( total_mb * mib * 5 / 100 ))
    if (( min_b < 1024 * mib )); then min_b=$(( 1024 * mib )); fi
    if (( min_b > max_b / 2 )); then min_b=$(( max_b / 2 )); fi

    echo "${min_b} ${max_b}"
}

firstboot_generate() {
    local working_dir="${PVE_WORKING_DIR:-/root}"
    local output_dir="${working_dir}/generated"
    local output_file="${output_dir}/first-boot.sh"

    mkdir -p "$output_dir"
    chmod 700 "$output_dir"

    log_info "Generating first-boot script..."

    local suite="${PVE_DEBIAN_SUITE:-trixie}"

    local interfaces_content hosts_content resolv_content
    interfaces_content="$(provider_render_interfaces "$FIRSTBOOT_WAN_PLACEHOLDER")"
    hosts_content="$(firstboot_render_hosts)"
    resolv_content="$(firstboot_render_resolv)"

    (
        umask 077
        {
            _fb_section_header
            _fb_section_vars "$suite"
            _fb_section_network "$interfaces_content"
            _fb_section_identity "$hosts_content" "$resolv_content"
            _fb_section_tuning
            if [[ "$PVE_FILESYSTEM" == "zfs" ]]; then
                _fb_section_zfs
            fi
            _fb_section_apt
            _fb_section_services
            if [[ "$PVE_NETWORK_MODE" == "nat" ]] && [[ "$PVE_ENABLE_DHCP" == true ]]; then
                _fb_section_dhcp
            fi
            _fb_section_nonag
            _fb_section_ssh
            _fb_section_backup
        } > "$output_file"
    )

    if declare -F luks_premium_inject_firstboot >/dev/null; then
        luks_premium_inject_firstboot "$output_file"
    fi
    if declare -F zfs_crypt_inject_firstboot >/dev/null; then
        zfs_crypt_inject_firstboot "$output_file"
    fi

    cat >> "$output_file" <<'FBDONE'

fb_log "First-boot configuration complete"
fb_log "Web UI: https://${FB_MAIN_IPV4}:8006"
FBDONE

    chmod 700 "$output_file"

    if command -v bash >/dev/null && ! bash -n "$output_file"; then
        die "Generated first-boot script has a syntax error: ${output_file}"
    fi

    ui_success "First-boot script generated"
    log_debug "First-boot script: ${output_file}"
}

_fb_section_header() {
    cat <<'FBHEADER'
#!/bin/bash
# Proxmox VE First-Boot Configuration Script
# Generated by pve-dedicated -- do not edit manually
#
# This script intentionally does NOT use `set -e`: it is a best-effort
# post-install configurator, and a transient failure in one optional step
# (a mirror hiccup, an already-loaded module) must not leave the rest of the
# system unconfigured. `-u` catches typos, `pipefail` catches silent
# pipeline errors; each step handles its own failure.
set -uo pipefail

LOG="/var/log/pve-first-boot.log"
exec > >(tee -a "$LOG") 2>&1
fb_log() { echo "[$(date '+%F %T')] $*"; }
fb_log "First-boot configuration starting..."
export DEBIAN_FRONTEND=noninteractive

fb_apt() {
    local attempt
    for attempt in 1 2 3; do
        if apt-get update -qq && apt-get install -yq "$@"; then
            return 0
        fi
        fb_log "apt install $* failed (attempt ${attempt}); retrying in 10s"
        sleep 10
    done
    return 1
}

FBHEADER
}

_fb_section_vars() {
    local suite="$1"
    local ceph_release="ceph-tentacle"
    [[ "$suite" == "bookworm" ]] && ceph_release="ceph-squid"

    echo "# --- Install-time values ---"
    _fb_var FB_HOSTNAME "$PVE_HOSTNAME"
    _fb_var FB_MAIN_IPV4 "$PVE_MAIN_IPV4"
    _fb_var FB_WAN_MAC "${PVE_MAC_ADDRESS,,}"
    _fb_var FB_WAN_IFACE_EXPECTED "${PVE_PREDICTED_IFACE:-${PVE_INTERFACE}}"
    _fb_var FB_WAN_PLACEHOLDER "$FIRSTBOOT_WAN_PLACEHOLDER"
    _fb_var FB_DEBIAN_SUITE "$suite"
    _fb_var FB_CEPH_RELEASE "$ceph_release"
    echo ""
}

_fb_section_network() {
    local interfaces_content="$1"

    cat <<'FBNET'
# --- Network interfaces ------------------------------------------------------
# Resolve the WAN NIC by MAC on the real hardware: the rescue system's
# naming prediction can differ from what this kernel/udev assigns.
fb_resolve_wan_iface() {
    local dev mac
    for dev in /sys/class/net/*; do
        [ -e "${dev}/device" ] || continue
        mac="$(cat "${dev}/address" 2>/dev/null)"
        if [ "${mac,,}" = "$FB_WAN_MAC" ]; then
            basename "$dev"
            return 0
        fi
    done
    return 1
}

WAN_IFACE="$(fb_resolve_wan_iface || true)"
if [ -z "$WAN_IFACE" ]; then
    WAN_IFACE="$FB_WAN_IFACE_EXPECTED"
    fb_log "WARN: no NIC with MAC ${FB_WAN_MAC}; using predicted name ${WAN_IFACE}"
elif [ "$WAN_IFACE" != "$FB_WAN_IFACE_EXPECTED" ]; then
    fb_log "NOTE: WAN NIC is ${WAN_IFACE} (rescue predicted ${FB_WAN_IFACE_EXPECTED})"
fi

cp -a /etc/network/interfaces /etc/network/interfaces.pve-installer 2>/dev/null || true
FBNET
    _fb_write_file /etc/network/interfaces.pve-dedicated-template INTERFACES_EOF "$interfaces_content"
    cat <<'FBNET'
sed "s/${FB_WAN_PLACEHOLDER}/${WAN_IFACE}/g" /etc/network/interfaces.pve-dedicated-template \
    > /etc/network/interfaces
fb_log "Network interfaces configured (WAN: ${WAN_IFACE})"

# Pin the WAN NIC name to its MAC so kernel/systemd upgrades cannot rename it
# (a rename on a remote server means losing access).
if ! printf '%s' "$WAN_IFACE" | grep -Eq '^eth[0-9]+$'; then
    mkdir -p /etc/systemd/network
    cat > /etc/systemd/network/10-pve-dedicated-wan.link <<LINK_EOF
# Written by pve-dedicated first-boot: keep the WAN NIC name stable.
[Match]
MACAddress=${FB_WAN_MAC}
Type=ether

[Link]
Name=${WAN_IFACE}
LINK_EOF
    fb_log "WAN NIC name pinned: ${FB_WAN_MAC} -> ${WAN_IFACE}"
fi

# Apply the new config now. The installer captured QEMU's user-mode DHCP
# lease (10.0.2.15) as the initial config; without reloading, every apt call
# below would fail on bare metal.
fb_log "Applying network configuration..."
if command -v ifreload >/dev/null 2>&1; then
    ifreload -a || fb_log "WARN: ifreload returned $?"
else
    systemctl restart networking || fb_log "WARN: networking restart returned $?"
fi

# Wait up to 120s for the gateway to answer. OVH switch-port authorisation
# can take 10-60s after the first link-up.
fb_log "Waiting for the default gateway..."
network_ok=0
for i in $(seq 1 60); do
    gw="$(ip -4 route show default 2>/dev/null | awk '/^default via/ {print $3; exit}')"
    if [ -n "$gw" ] && ping -c 1 -W 2 "$gw" >/dev/null 2>&1; then
        fb_log "Gateway ${gw} reachable after $(( i * 2 ))s"
        network_ok=1
        break
    fi
    sleep 2
done
if [ "$network_ok" -eq 0 ]; then
    fb_log "WARN: gateway not reachable after 120s; package installs below may fail"
fi
ip -brief addr 2>/dev/null || true
ip -brief route show default 2>/dev/null || true

FBNET
}

_fb_section_identity() {
    local hosts_content="$1"
    local resolv_content="$2"

    cat <<'FBID'
# --- Hostname, hosts, DNS ---
echo "$FB_HOSTNAME" > /etc/hostname
hostnamectl set-hostname "$FB_HOSTNAME" 2>/dev/null || true
FBID
    _fb_write_file /etc/hosts HOSTS_EOF "$hosts_content"
    _fb_write_file /etc/resolv.conf DNS_EOF "$resolv_content"
    cat <<'FBID'
fb_log "Hostname, /etc/hosts and DNS configured"

# Prefer IPv4 for name resolution and apt (provider IPv6 can be flaky).
grep -q '^precedence ::ffff:0:0/96  100' /etc/gai.conf 2>/dev/null \
    || echo 'precedence ::ffff:0:0/96  100' >> /etc/gai.conf
echo 'Acquire::ForceIPv4 "true";' > /etc/apt/apt.conf.d/99force-ipv4

FBID
}

_fb_section_tuning() {
    local modules="tcp_bbr"
    local sysctl_content
    sysctl_content="# Written by pve-dedicated first-boot
net.ipv4.ip_forward=1
net.ipv6.conf.all.forwarding=1
net.core.default_qdisc=fq
net.ipv4.tcp_congestion_control=bbr
net.ipv4.tcp_fastopen=3
vm.swappiness=10
kernel.panic=10
kernel.panic_on_oops=1
fs.inotify.max_user_watches=1048576
fs.inotify.max_user_instances=1048576
fs.inotify.max_queued_events=1048576"
    if [[ "$PVE_NETWORK_MODE" == "nat" ]]; then
        modules+=$'\n'"nf_conntrack"
        sysctl_content+="
net.netfilter.nf_conntrack_max=1048576
net.netfilter.nf_conntrack_tcp_timeout_established=28800"
    fi

    echo "# --- Kernel modules and sysctl tuning ---"
    _fb_write_file /etc/modules-load.d/pve-dedicated.conf MODULES_EOF "$modules"
    _fb_write_file /etc/sysctl.d/90-pve-dedicated.conf SYSCTL_EOF "$sysctl_content"
    cat <<'FBTUNE'
while read -r mod; do
    modprobe "$mod" 2>/dev/null || true
done < /etc/modules-load.d/pve-dedicated.conf
sysctl --system >/dev/null 2>&1 || true
fb_log "Kernel tuning applied (forwarding, BBR, fastopen, swappiness, panic, inotify)"

mkdir -p /etc/systemd/journald.conf.d
cat > /etc/systemd/journald.conf.d/90-pve-dedicated.conf <<'JOURNAL_EOF'
[Journal]
SystemMaxUse=64M
RuntimeMaxUse=64M
JOURNAL_EOF
systemctl restart systemd-journald 2>/dev/null || true
fb_log "Journald limited to 64M"

FBTUNE
}

_fb_section_zfs() {
    local total_kb total_mb limits arc_min arc_max
    total_kb="$(awk '/^MemTotal:/ {print $2; exit}' /proc/meminfo 2>/dev/null)"
    total_mb=$(( ${total_kb:-0} / 1024 ))
    limits="$(firstboot_zfs_arc_limits "$total_mb" "$PVE_ZFS_ARC_MAX")"
    read -r arc_min arc_max <<< "$limits"

    echo "# --- ZFS ARC limits (host RAM: ${total_mb} MiB) ---"
    _fb_var FB_ARC_MIN "$arc_min"
    _fb_var FB_ARC_MAX "$arc_max"
    cat <<'FBZFS'
rm -f /etc/modprobe.d/zfs.conf
cat > /etc/modprobe.d/99-zfs.conf <<ZFS_EOF
options zfs zfs_arc_min=${FB_ARC_MIN}
options zfs zfs_arc_max=${FB_ARC_MAX}
ZFS_EOF
echo "$FB_ARC_MAX" > /sys/module/zfs/parameters/zfs_arc_max 2>/dev/null || true
echo "$FB_ARC_MIN" > /sys/module/zfs/parameters/zfs_arc_min 2>/dev/null || true
update-initramfs -u -k all >/dev/null 2>&1 || fb_log "WARN: update-initramfs failed"
fb_log "ZFS ARC tuned: min=$(( FB_ARC_MIN / 1048576 ))MiB max=$(( FB_ARC_MAX / 1048576 ))MiB"

FBZFS
}

_fb_section_apt() {
    cat <<'FBAPT'
# --- APT sources: enterprise -> no-subscription ------------------------------
# Disable every repo that needs a subscription (PVE + Ceph, .list and .sources).
for f in /etc/apt/sources.list.d/*.list /etc/apt/sources.list.d/*.sources; do
    [ -f "$f" ] || continue
    if grep -q 'enterprise.proxmox.com' "$f" 2>/dev/null; then
        mv "$f" "${f}.disabled"
        fb_log "Disabled enterprise repo: $f"
    fi
done

if [ -s /etc/apt/sources.list ]; then
    mv /etc/apt/sources.list /etc/apt/sources.list.bak
fi

if [ "$FB_DEBIAN_SUITE" = "bookworm" ]; then
    echo "deb http://download.proxmox.com/debian/pve ${FB_DEBIAN_SUITE} pve-no-subscription" \
        > /etc/apt/sources.list.d/pve-no-subscription.list
    echo "deb http://download.proxmox.com/debian/${FB_CEPH_RELEASE} ${FB_DEBIAN_SUITE} no-subscription" \
        > /etc/apt/sources.list.d/ceph-no-subscription.list
else
    cat > /etc/apt/sources.list.d/proxmox.sources <<SOURCES_EOF
Types: deb
URIs: http://download.proxmox.com/debian/pve
Suites: ${FB_DEBIAN_SUITE}
Components: pve-no-subscription
Signed-By: /usr/share/keyrings/proxmox-archive-keyring.gpg
SOURCES_EOF
    cat > /etc/apt/sources.list.d/ceph.sources <<SOURCES_EOF
Types: deb
URIs: http://download.proxmox.com/debian/${FB_CEPH_RELEASE}
Suites: ${FB_DEBIAN_SUITE}
Components: no-subscription
Signed-By: /usr/share/keyrings/proxmox-archive-keyring.gpg
SOURCES_EOF
fi
fb_log "APT sources configured (pve-no-subscription + ${FB_CEPH_RELEASE} no-subscription)"

FBAPT
}

_fb_section_services() {
    cat <<'FBSERVICES'
# --- Services ---
systemctl disable --now rpcbind.service rpcbind.socket 2>/dev/null || true
fb_log "rpcbind disabled (re-enable it if you use NFSv3 storage)"

FBSERVICES
}

_fb_section_dhcp() {
    local prefix="${PVE_PRIVATE_SUBNET#*/}"
    local dhcp_start dhcp_end dhcp_gw netmask
    dhcp_start="$(net_ipv4_host "$PVE_PRIVATE_SUBNET" 100)"
    dhcp_end="$(net_ipv4_host "$PVE_PRIVATE_SUBNET" 200)"
    dhcp_gw="$PVE_PRIVATE_IP"
    netmask="$(net_prefix_to_netmask "$prefix")"

    local dns4="" dns
    for dns in $PVE_DNS_SERVERS; do
        [[ "$dns" == *:* ]] && continue
        dns4+="${dns4:+,}${dns}"
    done

    local dnsmasq_conf="# Written by pve-dedicated first-boot: DHCP for the NAT bridge only.
# port=0 disables the DNS server entirely, so this host never becomes a
# resolver on any interface.
port=0
interface=vmbr1
bind-interfaces
dhcp-range=${dhcp_start},${dhcp_end},${netmask},12h
dhcp-option=option:router,${dhcp_gw}"
    if [[ -n "$dns4" ]]; then
        dnsmasq_conf+=$'\n'"dhcp-option=option:dns-server,${dns4}"
    fi

    echo "# --- DHCP server (dnsmasq) on vmbr1 -- best effort ---"
    cat <<'FBDHCP'
fb_log "Installing dnsmasq for vmbr1 DHCP..."
if fb_apt dnsmasq; then
    rm -f /etc/dnsmasq.d/00-base.conf /etc/dnsmasq.d/vmbr1-dhcp.conf
FBDHCP
    _fb_write_file /etc/dnsmasq.d/pve-dedicated-vmbr1.conf DNSMASQ_EOF "$dnsmasq_conf"
    cat <<FBDHCP
    systemctl enable dnsmasq 2>/dev/null || true
    systemctl restart dnsmasq 2>/dev/null || fb_log "WARN: dnsmasq failed to start"
    fb_log "DHCP server configured on vmbr1 (${dhcp_start} - ${dhcp_end})"
else
    fb_log "WARN: dnsmasq install failed; VMs on vmbr1 need static IPs"
    fb_log "      Later: apt-get install dnsmasq and see docs/CONTRIBUTING.md"
fi

FBDHCP
}

_fb_section_nonag() {
    cat <<'FBNONAG'
# --- Subscription notice ------------------------------------------------------
# Re-applied by a dpkg hook after every package operation, so upgrades of
# proxmox-widget-toolkit do not bring the notice back.
cat > /usr/local/sbin/pve-dedicated-nonag <<'NONAG_EOF'
#!/bin/sh
# Written by pve-dedicated: hide the "No valid subscription" dialog.
LIB="/usr/share/javascript/proxmox-widget-toolkit/proxmoxlib.js"
[ -f "$LIB" ] || exit 0
grep -q 'void({ //Ext.Msg.show' "$LIB" && exit 0
sed -Ezi.bak "s/(Ext.Msg.show\(\{\s+title: gettext\('No valid sub)/void\(\{ \/\/\1/g" "$LIB" || exit 0
systemctl try-restart pveproxy.service >/dev/null 2>&1 || true
NONAG_EOF
chmod 755 /usr/local/sbin/pve-dedicated-nonag
echo 'DPkg::Post-Invoke { "/usr/local/sbin/pve-dedicated-nonag || true"; };' \
    > /etc/apt/apt.conf.d/99-pve-dedicated-nonag
/usr/local/sbin/pve-dedicated-nonag
fb_log "Subscription notice removed (persisted via dpkg hook)"

FBNONAG
}

_fb_section_ssh() {
    if [[ -z "$PVE_SSH_KEYS" ]]; then
        cat <<'FBSSH_SKIP'
# --- SSH hardening SKIPPED (no keys provided) ---
# To harden later: add your key to /root/.ssh/authorized_keys, then create
# /etc/ssh/sshd_config.d/99-hardening.conf with
#   PermitRootLogin prohibit-password
#   PasswordAuthentication no
# and run: sshd -t && systemctl restart ssh
fb_log "SSH hardening skipped (no keys provided)"

FBSSH_SKIP
        return 0
    fi

    echo "# --- SSH keys and hardening ---"
    echo "mkdir -p /root/.ssh && chmod 700 /root/.ssh"
    _fb_write_file /root/.ssh/authorized_keys SSHKEYS_EOF "$PVE_SSH_KEYS"
    cat <<'FBSSH'
chmod 600 /root/.ssh/authorized_keys

# On Proxmox /root/.ssh/authorized_keys may be a symlink into pmxcfs
# (/etc/pve/priv/authorized_keys); only copy when they are separate files.
if [ -d /etc/pve/priv ]; then
    src_path="$(readlink -f /root/.ssh/authorized_keys 2>/dev/null || true)"
    dst_path="$(readlink -f /etc/pve/priv/authorized_keys 2>/dev/null || true)"
    if [ -n "$src_path" ] && [ "$src_path" = "$dst_path" ]; then
        fb_log "SSH keys already cluster-synced via symlink"
    elif cp /root/.ssh/authorized_keys /etc/pve/priv/authorized_keys 2>/dev/null; then
        fb_log "SSH keys installed to /etc/pve/priv/authorized_keys (cluster-synced)"
    else
        fb_log "WARN: failed to copy SSH keys to /etc/pve/priv (continuing)"
    fi
fi

# Drop-in config; PermitRootLogin must stay prohibit-password (clustering).
cat > /etc/ssh/sshd_config.d/99-hardening.conf <<'SSHD_EOF'
# Proxmox-safe SSH hardening (cluster-compatible), written by pve-dedicated
PermitRootLogin prohibit-password
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitEmptyPasswords no
PubkeyAuthentication yes
MaxAuthTries 3
X11Forwarding no
SSHD_EOF

if sshd -t 2>/dev/null; then
    systemctl restart ssh 2>/dev/null || systemctl restart sshd 2>/dev/null || true
    fb_log "SSH hardened: key-only root login"
else
    rm -f /etc/ssh/sshd_config.d/99-hardening.conf
    fb_log "WARN: sshd rejected the hardening drop-in; it was removed (password login still enabled)"
fi

FBSSH
}

_fb_section_backup() {
    cat <<'FBBACKUP'
# --- vzdump defaults ---
if [ -f /etc/vzdump.conf ]; then
    sed -i -e "s/^#\?bwlimit:.*/bwlimit: 0/" \
           -e "s/^#\?ionice:.*/ionice: 5/" \
           -e "s/^#\?pigz:.*/pigz: 1/" /etc/vzdump.conf
fi
fb_apt pigz >/dev/null 2>&1 || true
fb_log "vzdump tuned (no bandwidth limit, pigz for gzip backups)"
FBBACKUP
}

# Back-compat shim for the SSH-based fallback path.
firstboot_render_interfaces() {
    provider_render_interfaces "$@"
}

firstboot_render_hosts() {
    cat <<HOSTS
127.0.0.1 localhost.localdomain localhost
${PVE_MAIN_IPV4} ${PVE_FQDN} ${PVE_HOSTNAME}

# IPv6
::1     ip6-localhost ip6-loopback
fe00::0 ip6-localnet
ff00::0 ip6-mcastprefix
ff02::1 ip6-allnodes
ff02::2 ip6-allrouters
ff02::3 ip6-allhosts
HOSTS
    if [[ -n "$PVE_IPV6" ]]; then
        echo "${PVE_IPV6} ${PVE_FQDN} ${PVE_HOSTNAME}"
    fi
}

firstboot_render_resolv() {
    if [[ "$PVE_FQDN" == *.* ]]; then
        echo "search ${PVE_FQDN#*.}"
    fi
    local dns
    for dns in $PVE_DNS_SERVERS; do
        echo "nameserver ${dns}"
    done
}

# First-boot hooks need proxmox-auto-install-assistant with --on-first-boot
# (Proxmox VE 8.3+).
firstboot_is_supported() {
    if ! command -v proxmox-auto-install-assistant &>/dev/null; then
        return 1
    fi
    proxmox-auto-install-assistant prepare-iso --help 2>&1 | grep -q 'on-first-boot'
}
